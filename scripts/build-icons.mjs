#!/usr/bin/env node
/**
 * Copies the Phosphor icons the site uses into src/lib/icons.gen.ts, so the
 * bundle carries ~60 icons instead of the whole set.
 *
 * Add a name (Phosphor's file name, e.g. "shopping-bag") to ICONS below, run
 * `node scripts/build-icons.mjs`, then use <Icon name="shopping-bag" />.
 * Browse the set at https://phosphoricons.com.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ICONS = [
  "gift", "house", "magnifying-glass", "plus", "heart", "user", "user-circle", "users", "users-three",
  "user-plus", "user-minus", "user-check", "bell", "list", "list-heart", "gear", "sign-out", "sign-in", "globe",
  "caret-down", "caret-right", "caret-left", "check", "check-circle", "x", "trash", "pencil-simple", "star",
  "link", "link-simple", "share-network", "copy", "arrow-left", "arrow-right", "arrow-square-out", "camera",
  "image", "cake", "calendar-blank", "lock", "lock-open", "eye", "eye-slash", "envelope", "envelope-simple",
  "sparkle", "tag", "shopping-bag", "hand-heart", "coffee", "confetti", "qr-code", "question", "warning",
  "info", "google-logo", "paper-plane-tilt", "password", "upload-simple", "dots-three", "bookmark-simple",
  "clock", "map-pin", "globe-hemisphere-east", "storefront", "smiley", "hand-waving", "chat-circle-dots",
  "shield-check", "key", "palette", "moon", "sun", "snowflake", "egg", "tree-evergreen", "balloon",
  "lightning", "rocket-launch", "seal-check", "tray", "clipboard-text", "scroll", "image-square",
  "lightbulb", "fire", "package", "arrow-counter-clockwise", "chart-bar", "device-mobile", "bell-ringing",
  "bell-slash", "users-four", "hand-coins", "chart-line-up", "flag", "prohibit", "bug", "download-simple",
  "arrow-clockwise", "envelope-open", "eye-closed", "cookie", "detective",
  // Name-only gifts get an icon that fits the name (lib/gift-icon.ts).
  "book-open-text", "drop", "t-shirt", "sneaker", "game-controller", "headphones", "laptop", "watch", "diamond",
  "flower-tulip", "music-notes", "airplane-tilt", "puzzle-piece", "baby", "paint-brush", "barbell", "bicycle",
  "paw-print", "cooking-pot", "wine", "ticket", "plant", "television", "dress", "handbag",
  "whatsapp-logo",
  "telegram-logo",
  "messenger-logo",
];
const WEIGHTS = ["duotone", "regular", "fill", "bold"];

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assets = join(root, "node_modules/@phosphor-icons/core/assets");
const out = {};
for (const name of ICONS) {
  out[name] = {};
  for (const w of WEIGHTS) {
    const file = join(assets, w, w === "regular" ? `${name}.svg` : `${name}-${w}.svg`);
    const svg = readFileSync(file, "utf8");
    out[name][w] = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  }
}
const ts = `// Generated by scripts/build-icons.mjs from @phosphor-icons/core (MIT). Do not edit.
export type IconWeight = ${WEIGHTS.map((w) => JSON.stringify(w)).join(" | ")};
export const ICONS: Record<string, Record<IconWeight, string>> = ${JSON.stringify(out)};
`;
writeFileSync(join(root, "src/lib/icons.gen.ts"), ts);
console.log(`${ICONS.length} icons × ${WEIGHTS.length} weights → src/lib/icons.gen.ts (${Math.round(ts.length / 1024)} KB)`);
